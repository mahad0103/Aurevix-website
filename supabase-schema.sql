-- Run this in Supabase SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  role text not null default 'reader' check (role in ('reader','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  summary text not null,
  content text not null,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.posts enable row level security;

create or replace function public.is_aurevix_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create policy "Users can read their own profile"
on public.profiles for select to authenticated
using (id = auth.uid());

create policy "Anyone can read published posts"
on public.posts for select to anon, authenticated
using (published = true or public.is_aurevix_admin());

create policy "Only Aurevix admin can insert posts"
on public.posts for insert to authenticated
with check (public.is_aurevix_admin());

create policy "Only Aurevix admin can update posts"
on public.posts for update to authenticated
using (public.is_aurevix_admin())
with check (public.is_aurevix_admin());

create policy "Only Aurevix admin can delete posts"
on public.posts for delete to authenticated
using (public.is_aurevix_admin());

